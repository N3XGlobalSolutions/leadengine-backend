"""Safety and formatting validator for outgoing WhatsApp messages."""

import re
from typing import List
from app.services.ai.outbound.conversation_pipeline import OutboundAISession
from app.core.logging_config import get_logger

logger = get_logger(__name__)

# Basic profanity list for business conversations
PROFANITY_BLACKLIST = {
    "abuse", "scam", "fraud", "scammer", "spam", "f**k", "shit", "bitch", "asshole"
}


class ResponseValidator:
    """Post-processing validation checking safety, length, and format of AI responses."""

    def validate_response(self, session: OutboundAISession, text: Optional[str]) -> str:
        """Validate, sanitize, and format response string.

        Args:
            session: Outbound session variables
            text: Raw output string generated by LLM

        Returns:
            Cleaned and verified output string
        """
        # 1. Fallback for empty replies
        if not text or not text.strip():
            logger.warning("[ResponseValidator] Received empty response from model.")
            return "I'm here to help. Could you please clarify your question?"

        cleaned = text.strip()

        # 2. Character Length Enforcer
        max_len = session.agent_settings.max_response_length if session.agent_settings else 500
        if len(cleaned) > max_len:
            logger.warning(f"[ResponseValidator] Response length ({len(cleaned)}) exceeds limit ({max_len}). Truncating.")
            # Graceful truncation at last sentence/space
            truncated = cleaned[:max_len]
            last_space = truncated.rfind(" ")
            if last_space > 0:
                cleaned = truncated[:last_space] + "..."
            else:
                cleaned = truncated + "..."

        # 3. Clean up unsupported markdown formatting (WhatsApp compat)
        # WhatsApp supports *bold*, _italics_, ~strikethrough~, and ```monospace```.
        # It does NOT support headers (#), markdown link notation [text](url), HTML tags, or raw code blocks.
        
        # Replace Markdown link notation [Link Name](http://...) with "Link Name (http://...)"
        cleaned = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", cleaned)
        
        # Strip square brackets commonly generated by LLM citations e.g. "We offer CRM [Source 1]" -> "We offer CRM"
        cleaned = re.sub(r"\[(Source|source|doc|Document)\s*\d*\]", "", cleaned)
        cleaned = re.sub(r"\[\d+\]", "", cleaned)  # Strip standard [1] style citations

        # Strip remaining isolated brackets or brackets wrapping text
        cleaned = cleaned.replace("[", "").replace("]", "")

        # Strip HTML-like tags (e.g. <search>, etc.)
        cleaned = re.sub(r"<[^>]+>", "", cleaned)

        # 4. Hallucinated URL Check
        # Ensure that any links shared are in our allowed list, or are from the product catalog/brochures
        urls = re.findall(r"https?://[^\s/$.?#].[^\s]*", cleaned)
        if urls:
            allowed_urls = []
            
            # Extract allowed brochure and image URLs from session products
            for p in session.selected_products:
                if p.brochure_pdf:
                    allowed_urls.append(p.brochure_pdf)
                allowed_urls.extend(p.images)
                allowed_urls.extend(p.gallery)

            for url in urls:
                # Basic domain validation: if it's a hallucinated or external url not explicitly listed
                # in the products or RAG documents, strip it or replace with business support URL.
                is_allowed = any(url in allowed for allowed in allowed_urls) or "meet.google.com" in url or "qbotglobal.com" in url
                if not is_allowed:
                    logger.warning(f"[ResponseValidator] Stripping unauthorized/hallucinated URL: '{url}'")
                    cleaned = cleaned.replace(url, "")

        # 5. Profanity & Business Safety Check
        words = re.findall(r"\b\w+\b", cleaned.lower())
        for w in words:
            if w in PROFANITY_BLACKLIST:
                logger.warning(f"[ResponseValidator] Safety alert: blacklisted word '{w}' detected in reply.")
                # Return generic sales fallback message instead of sending profanity to prospects
                return "Our goal is to assist you with the best solutions. How can we help you move forward?"

        # Replace double spaces and clean whitespace artifacts from regex replacements
        cleaned = re.sub(r"\s+", " ", cleaned).strip()

        return cleaned


# Global validator singleton
response_validator = ResponseValidator()
